export type CharMapKey = keyof typeof charMaps;

export function isChinese(char: string): boolean {
  const code = char.charCodeAt(0);
  return (code >= 0x4e00 && code <= 0x9fff) ||
    (code >= 0x3400 && code <= 0x4dbf) ||
    (code >= 0x20000 && code <= 0x2a6df);
}

export function transformTextWithChineseCheck(text: string, mapName: CharMapKey): string {
  const map = charMaps[mapName];
  return text.split("").map((char) => {
    if (isChinese(char)) return char;
    return (map as Record<string, string>)[char] || char;
  }).join("");
}

