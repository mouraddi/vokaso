export function upsideDownTextWithChineseCheck(text: string): string {
  return text.split("").map((char) => {
    if (isChinese(char)) return char;
    return flipMap[char] || char;
  }).reverse().join("");
}

export function reverseText(text: string): string {
  return text.split("").reverse().join("");
}

export function wideText(text: string): string {
  return text.split("").join(" ");
}

export function strikethroughText(text: string): string {
  return text.split("").map((char) => `${char}\u0336`).join("");
}

